/**
 * voice.ts — 语音口述 → 表达式文本的规范化（M3 语音输入入口，v1「语音页签」的等价能力）
 * 纯函数、确定性：只做「词 → 符号」替换与全角/空白归一，不做语法补全（补全动作交给用户）。
 * 规则按词长降序应用，避免「的平方」被「的」抢先吃掉。
 * 正确性由 parity.mjs 闭式真值钉死（运算符/平方/负小数/撇与等于/ASCII 幂等）。
 */

const RULES: ReadonlyArray<readonly [string, string]> = [
  ['两撇', "''"],
  ['一撇', "'"],
  ['撇', "'"],
  ['乘以', '*'],
  ['除以', '/'],
  ['等于', '='],
  ['左括号', '('],
  ['右括号', ')'],
  ['的平方', '^2'],
  ['的立方', '^3'],
  ['平方', '^2'],
  ['立方', '^3'],
  ['的', ''],
  ['乘', '*'],
  ['除', '/'],
  ['加', '+'],
  ['减', '-'],
  ['负', '-'],
  ['（', '('],
  ['）', ')'],
  ['，', ','],
  ['、', ''],
  ['。', ''],
  ['零', '0'],
  ['一', '1'],
  ['二', '2'],
  ['两', '2'],
  ['三', '3'],
  ['四', '4'],
  ['五', '5'],
  ['六', '6'],
  ['七', '7'],
  ['八', '8'],
  ['九', '9'],
  ['点', '.'],
];

/** 口述文本 → 表达式文本：词→符号替换 + 去掉所有空白（含全角空格）；ASCII 输入保持幂等 */
export function voiceToExpr(text: string): string {
  let s = String(text ?? '');
  for (const [from, to] of RULES) s = s.split(from).join(to);
  return s.replace(/[\s\u3000]+/g, '');
}
